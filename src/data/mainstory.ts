export const ALL_STORY: StoryChapter[] = [...MAIN, ...HIDDEN]
export const STORY_MAP: Record<string, StoryChapter> = Object.fromEntries(ALL_STORY.map(c => [c.id, c]))

// —— 性别线：传「女」时正卷 22 卷正文换为女修线（隐藏卷共用）——
export function chaptersForGender(gender: string): StoryChapter[] {
  if (gender !== '女') return ALL_STORY
  return ALL_STORY.map(c => (STORY_F[c.id] ? { ...c, text: STORY_F[c.id] } : c))
}
export function chapterForGender(id: string, gender: string): StoryChapter | undefined {
  const c = STORY_MAP[id]
  if (!c) return undefined
  return gender === '女' && STORY_F[id] ? { ...c, text: STORY_F[id] } : c
}

// 某个长阶阶数解锁的正卷章节
export function storyAtStage(n: number): StoryChapter | null {
  return MAIN.find(c => c.stage === n) || null
}

// 章节解锁判定（长阶阶数达标 + 额外条件）
export function storyChapterReady(ch: StoryChapter, ctx: StoryCtx): boolean {
  return ctx.stage >= ch.stage && (!ch.cond || ch.cond(ctx))
}
