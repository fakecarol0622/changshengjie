const SECT_CORE = ['剑', '刀', '丹', '药', '器', '阵', '符', '兽', '灵', '风', '雷', '星', '月', '火', '冰', '玄', '山', '海', '云']
const SECT_TYPE = ['宗', '门', '阁', '谷', '观', '殿', '教']
const SECT_BIG = ['山庄', '书院', '剑冢', '道场']
// 已有的六大门派，避免随机撞名
const SECT_TAKEN = ['青霄剑宗', '丹霞谷', '天工阁', '万兽山', '幽冥宗', '太虚观']

/** 随机宗门名：修饰词（+核心字）+ 门派型（如「玄天宗」「青云剑宗」「栖霞山庄」） */
export function randomSectName(): string {
  for (let i = 0; i < 12; i++) {
    const r = ri(1, 100)
    let n: string
    if (r <= 14) n = pick(SECT_PREFIX) + pick(SECT_BIG)
    else if (r <= 59) n = pick(SECT_PREFIX) + pick(SECT_CORE) + pick(SECT_TYPE)
    else n = pick(SECT_PREFIX) + pick(SECT_TYPE)
    if (!SECT_TAKEN.includes(n)) return n
  }
  return pick(SECT_PREFIX) + pick(SECT_CORE) + pick(SECT_TYPE)
}

/** 随机道号：二字雅号 / 修饰词单用 / 修饰词+身份（如「参同」「望岳」「青云散人」「紫霄仙子」） */
export function randomDaoName(gender: string = '男'): string {
  const r = ri(1, 100)
  if (r <= 20) return pick(DAO_ELEGANT)
  if (r <= 32) return pick(DAO_PREFIX)
  const suffix = gender === '女' ? [...DAO_SUFFIX, ...DAO_SUFFIX_F] : [...DAO_SUFFIX, ...DAO_SUFFIX_M]
  return pick(DAO_PREFIX) + pick(suffix)
}

